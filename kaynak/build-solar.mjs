import { build } from 'vite';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('.',import.meta.url));
const result=await build({root,configFile:false,build:{write:false,target:'es2022',rollupOptions:{input:path.join(root,'ay-krater.html'),output:{inlineDynamicImports:true}}}});
const outputs=Array.isArray(result)?result.flatMap(r=>r.output):result.output;
const entry=outputs.find(f=>f.type==='chunk'&&f.isEntry);
if(!entry)throw new Error('Missing entry bundle');
let html=await readFile(path.join(root,'ay-krater.html'),'utf8');
html=html.replace(/<script type="module" src="\.\/src\/crater-ecosystem\.mjs"><\/script>/,()=>'<script type="module">'+entry.code.replaceAll('</script','<\\/script')+'</script>');
await writeFile(path.resolve(root,'../AY-KRATER-EKOSISTEM.html'),html);
